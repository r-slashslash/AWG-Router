/* Язык: по языку браузера/системы. Запоминается только ручной выбор,
   и только если он отличается от языка браузера — иначе панель следует за браузером. */
const LANG_KEY = "awgr.lang";
function browserLang() {
  const list = navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || "en"];
  for (const tag of list) {
    const l = String(tag).slice(0, 2).toLowerCase();
    if (I18N[l]) return l;
  }
  return "en";
}
let LANG = (() => {
  try { const s = localStorage.getItem(LANG_KEY); if (s && I18N[s]) return s; } catch { /* нет хранилища */ }
  return browserLang();
})();

function setLang(l, chosenByUser = false) {
  LANG = I18N[l] ? l : "en";
  if (chosenByUser) {
    try {
      if (LANG === browserLang()) localStorage.removeItem(LANG_KEY);
      else localStorage.setItem(LANG_KEY, LANG);
    } catch { /* нет хранилища */ }
  }
  document.documentElement.lang = LANG;
  document.documentElement.dir = LANGS[LANG].dir;
}
setLang(LANG);

const _plural = {};
function _pick(v, n) {
  if (typeof v === "string") return v;
  const pr = _plural[LANG] || (_plural[LANG] = new Intl.PluralRules(LANG));
  return v[pr.select(n)] ?? v.other ?? v.many ?? v.one;
}
function fmtNum(n) { return Number(n).toLocaleString(LANG); }

/* Разделители: перечисление, фразы, ссылки */
const SEP = {
  list: { zh: "、", fa: "، " }, phrase: { zh: "，", fa: "، " }, refs: { zh: "；", fa: "؛ " },
};
function sep(kind) { return SEP[kind][LANG] ?? (kind === "refs" ? "; " : ", "); }
/* Для письма справа налево изолируем вставки (имена, IP), иначе латиница «переезжает» */
function _iso(x) { return LANGS[LANG].dir === "rtl" ? "\u2068" + x + "\u2069" : x; }

function _fill(s, params, wrap) {
  return s.replace(/\{(\w+)\}/g, (_, k) => {
    if (k === "n" && "n" in params) return wrap(params.nText ?? fmtNum(params.n), true);
    return k in params ? wrap(params[k], false) : `{${k}}`;
  });
}
/** Текст по ключу (обычная строка). Параметр n — число для склонения, nText — как его показать. */
function t(key, params = {}) {
  const v = I18N[LANG][key] ?? I18N.en[key] ?? key;
  return _fill(_pick(v, params.n ?? 0), params, (x, isNum) => (isNum ? String(x) : _iso(String(x))));
}
/** То же для вставки в HTML: текст экранируется, параметры вставляются как готовый HTML. */
function th(key, params = {}) {
  const v = I18N[LANG][key] ?? I18N.en[key] ?? key;
  return _fill(esc(_pick(v, params.n ?? 0)), params, (x, isNum) => (isNum ? esc(x) : String(x)));
}
